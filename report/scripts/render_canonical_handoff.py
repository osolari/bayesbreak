def ascii_dashes(text: str) -> str:
    return str(text).replace("—", "--").replace("–", "--").replace("−", "-")


def tex_escape(text: Any) -> str:
    text = ascii_dashes(str(text))
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(ch, ch) for ch in text)


def split_items(value: str) -> list[str]:
    return [part.strip() for part in str(value).split(";") if part.strip()]


def tex_itemize(items: list[str], *, path_mode: bool = False) -> str:
    if not items:
        return r"\emph{None declared.}"
    lines = [r"\begin{itemize}[leftmargin=1.7em,itemsep=1.5pt,topsep=2pt]"]
    for item in items:
        if path_mode:
            lines.append(r"\item \path{" + ascii_dashes(item) + "}")
        else:
            lines.append(r"\item " + tex_escape(item))
    lines.append(r"\end{itemize}")
    return "\n".join(lines)


def path_list(value: str) -> str:
    return tex_itemize(split_items(value), path_mode=True)


def prose_list(value: str) -> str:
    return tex_itemize([item + ("" if item.endswith(".") else ".") for item in split_items(value)])


def tex_table_rows(records: list[dict[str, Any]], fields: list[str]) -> list[str]:
    rows: list[str] = []
    for record in records:
        cells = [tex_escape(record.get(field, "")) for field in fields]
        rows.append(" & ".join(cells) + r" \\")
    return rows


