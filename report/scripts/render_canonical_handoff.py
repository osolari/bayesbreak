def render_sync_manifest(data: dict[str, Any]) -> str:
    digest = hashlib.sha256(SRC.read_bytes()).hexdigest()
    manifest = {
        "handoff_id": data["handoff_id"],
        "phase": data["phase"],
        "canonical_json": str(SRC.relative_to(ROOT)),
        "canonical_json_sha256": digest,
        "generated_files": [
            str(TEX_DETAIL.relative_to(ROOT)),
            str(TEX_SUMMARY.relative_to(ROOT)),
        ],
        "counts": {
            "tasks": len(data["tasks"]),
            "experiments": len(data["experiments"]),
            "claims": len(data["claims"]),
            "results": len(data["results"]),
            "failure_states": len(data["failure_states"]),
            "stages": len(data["stage_sequence"]),
        },
    }
    return json.dumps(manifest, indent=2) + "\n"


def main() -> None:
    data = json.loads(SRC.read_text())
    TEX_DETAIL.write_text(render_detail(data))
    TEX_SUMMARY.write_text(render_summary(data))
    SYNC_MANIFEST.write_text(render_sync_manifest(data))
    print(
        f"rendered {len(data['tasks'])} tasks, {len(data['experiments'])} experiments, "
        f"{len(data['claims'])} claims, and {len(data['results'])} results"
    )


if __name__ == "__main__":
    main()
