        r"\caption{Implementation task registry. Detailed files, interfaces, and invariants are in Appendix~\ref{app:coding-handoff}.}\label{tab:code-tasks}\\",
        r"\toprule",
        r"\textbf{ID} & \textbf{Work item} & \textbf{Acceptance criterion}\\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"\textbf{ID} & \textbf{Work item} & \textbf{Acceptance criterion}\\",
        r"\midrule",
        r"\endhead",
